void Clockwise() {
HAL_GPIO_WritePin(GPIO_IN1, GPIO_PIN_IN1, GPIO_PIN_SET);
HAL_GPIO_WritePin(GPIO_IN2, GPIO_PIN_IN2, GPIO_PIN_RESET);
HAL_GPIO_WritePin(GPIO_ENA, GPIO_PIN_ENA, GPIO_PIN_SET);
}
void Counterclockwise() {
HAL_GPIO_WritePin(GPIO_IN1, GPIO_PIN_IN1, GPIO_PIN_RESET);
HAL_GPIO_WritePin(GPIO_IN2, GPIO_PIN_IN2, GPIO_PIN_SET);
HAL_GPIO_WritePin(GPIO_ENA, GPIO_PIN_ENA, GPIO_PIN_SET);
}
void Stop() {
HAL_GPIO_WritePin(GPIO_IN1, GPIO_PIN_IN1, GPIO_PIN_RESET);
HAL_GPIO_WritePin(GPIO_IN2, GPIO_PIN_IN2, GPIO_PIN_RESET);
HAL_GPIO_WritePin(GPIO_ENA, GPIO_PIN_ENA, GPIO_PIN_RESET);
}



volatile long pulse;
/*Using external interupt to count the encoder pulse*/
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin) {
if (HAL_GPIO_ReadPin(GPIOA, GPIO_PIN_1) == 0) {
pulse--;
} else {
pulse++;
}
}

/*Function to generate PWM to control the ENA pin of module L298N*/
void Output_PWM(TIM_HandleTypeDef *htim, uint32_t Channel, float Duty_Cycle) {
Duty_Cycle = Duty_Cycle / 100 * htim->Instance->ARR;
__HAL_TIM_SET_COMPARE(htim, Channel, (uint16_t)Duty_Cycle);
}


void PositionalControl() {
if (output > 0) {
Clockwise();
Output_PWM(&htim4, TIM_CHANNEL_1, output);
}
if (output < 0) {
Counterclockwise();
Output_PWM(&htim4, TIM_CHANNEL_1, -output);
}
if (output == 0) {
Stop();
Output_PWM(&htim4, TIM_CHANNEL_1, output);
}
}

void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim) {
/*Using timer interupt TIM1 to measure the speed of the motor*/
if (htim == &htim1) {
current_pulse_speed = pulse;
speed = (current_pulse_speed - previous_pulse_speed)/300
/ Delta_time_speed*60;
previous_pulse_speed = current_pulse_speed;
}

/*Using timer interupt 2 to control the motor speed*/
if (htim == &htim2) {
current_measurement_value = speed;
error = setpoint - current_measurement_value;
integral = integral + (error * Delta_t);
derivative = (error - previous_error) / Delta_t;
output = (Kp * error) + (Ki * integral) + (Kd * derivative);
if (output > 100)
output = 100;
if (output < -100)
output = -100;
previous_error = error;
PositionalControl();
}
}
